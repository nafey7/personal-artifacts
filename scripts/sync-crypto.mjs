#!/usr/bin/env node
// The CLI package is the source of truth for crypto code, because npm is
// where a person can read it before it runs. The viewer page needs the same
// code as a plain script, so this turns cli/wordlist.js + cli/crypto.js into
// public/artifact-crypto.v1.js — one file, no modules, one global — and
// records the SHA-384 of every script the viewer loads in lib/integrity.js,
// which the /a/<slug> route puts in each script tag's integrity attribute.
//
//   node scripts/sync-crypto.mjs           write both files
//   node scripts/sync-crypto.mjs --check   exit 1 if either is out of date
//
// `npm test` runs the check, and so does `prebuild`, so a hand edit to the
// generated copy cannot ship: it would differ from what this produces.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => readFileSync(join(root, path), "utf8");

export const GENERATED = "public/artifact-crypto.v1.js";
export const INTEGRITY_FILE = "lib/integrity.js";
// Every script the viewer loads with integrity=, generated or not.
export const PINNED = ["public/artifact-crypto.v1.js", "public/artifact-view.v1.js"];

export function build() {
  const wordlist = read("cli/wordlist.js");
  const crypto = read("cli/crypto.js");

  // The names the module exports become the fields of one global.
  const names = [];
  const strip = (source) =>
    source
      .replace(/^import .*\n/gm, "")
      .replace(/^export (?:async )?(?:function|const|let) (\w+)/gm, (line, name) => {
        names.push(name);
        return line.replace(/^export /, "");
      });

  const body = `${strip(wordlist)}\n${strip(crypto)}`;
  if (/^export /m.test(body)) throw new Error("an export was not recognised — add its form to sync-crypto");

  return `/* Generated by scripts/sync-crypto.mjs from cli/wordlist.js and cli/crypto.js.
   Do not edit here: change the source in the CLI package and run the script.
   The same code is published on npm as personal-artifact, where it can be
   read before it runs. */
(function (global) {
"use strict";
${body}
global.ArtifactCrypto = { ${names.join(", ")} };
})(typeof window !== "undefined" ? window : globalThis);
`;
}

export function integrity(contents) {
  return `sha384-${createHash("sha384").update(contents).digest("base64")}`;
}

export function integrityFile(hashes) {
  return `// Generated by scripts/sync-crypto.mjs. Do not edit.
//
// Subresource integrity for the scripts the artifact viewer loads. A page
// that decrypts in the browser is only as honest as the script that does it,
// so the route names each script's hash and the browser refuses a copy that
// differs — a modified deploy cannot quietly swap in one that posts keys
// home without the hash here changing too, and this file is in the open
// source repository.
export const INTEGRITY = ${JSON.stringify(hashes, null, 2)};
`;
}

export function expected() {
  const generated = build();
  const hashes = {};
  for (const path of PINNED) {
    const contents = path === GENERATED ? generated : read(path);
    hashes[path.replace(/^public\//, "")] = integrity(contents);
  }
  return { generated, integrity: integrityFile(hashes) };
}

// Which of the two files differ from what the sources say they should be.
export function stale() {
  const want = expected();
  const out = [];
  const same = (path, text) => {
    try {
      return read(path) === text;
    } catch {
      return false;
    }
  };
  if (!same(GENERATED, want.generated)) out.push(GENERATED);
  if (!same(INTEGRITY_FILE, want.integrity)) out.push(INTEGRITY_FILE);
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = stale();
  if (process.argv.includes("--check")) {
    if (out.length) {
      console.error(`out of date: ${out.join(", ")} — run node scripts/sync-crypto.mjs`);
      process.exit(1);
    }
    console.log("crypto scripts are in sync");
  } else {
    const want = expected();
    writeFileSync(join(root, GENERATED), want.generated);
    writeFileSync(join(root, INTEGRITY_FILE), want.integrity);
    console.log(out.length ? `updated ${out.join(", ")}` : "already in sync");
  }
}
